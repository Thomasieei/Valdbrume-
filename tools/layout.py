LOTS = []
def L(x0, z0, x1, z1, floors, preset, fronts, var=0, name=''):
    st, g, b, t, r = P[preset]
    LOTS.append(Lot(x0, z0, x1, z1, floors, st, fronts, g, b, t, r, var, name))

def block(x0, z0, x1, z1, corners, sides, depth=14):
    """corners : {'NO': (wx, wz, étages, préréglage, var)}, présents seulement
    sur les angles de rue. sides : {'N': [(largeur, étages, préréglage, var),
    ...]} de l'ouest vers l'est (N, S) ou du nord vers le sud (E, O) ;
    la largeur None prend le reste exact du côté."""
    c = corners
    def cw(k, axis):
        return c[k][0 if axis == 'x' else 1] if k in c else 0
    for k, (wx, wz, fl, pr, v) in c.items():
        fr = {'NO': ['N', 'O'], 'NE': ['N', 'E'], 'SE': ['S', 'E'], 'SO': ['S', 'O']}[k]
        fr = [f for f in fr if f in sides]
        if k == 'NO': L(x0, z0, x0+wx, z0+wz, fl, pr, fr, v)
        if k == 'NE': L(x1-wx, z0, x1, z0+wz, fl, pr, fr, v)
        if k == 'SE': L(x1-wx, z1-wz, x1, z1, fl, pr, fr, v)
        if k == 'SO': L(x0, z1-wz, x0+wx, z1, fl, pr, fr, v)
    for side, lots in sides.items():
        if side in ('N', 'S'):
            a = x0 + cw('NO' if side == 'N' else 'SO', 'x')
            b = x1 - cw('NE' if side == 'N' else 'SE', 'x')
        else:
            a = z0 + cw('NE' if side == 'E' else 'NO', 'z')
            b = z1 - cw('SE' if side == 'E' else 'SO', 'z')
        p = a
        for i, (w, fl, pr, v) in enumerate(lots):
            if w is None: w = b - p
            assert w > 0 and (w % 2 == 0), (x0, z0, side, i, w)
            if side == 'N': L(p, z0, p+w, z0+depth, fl, pr, ['N'], v)
            if side == 'S': L(p, z1-depth, p+w, z1, fl, pr, ['S'], v)
            if side == 'E': L(x1-depth, p, x1, p+w, fl, pr, ['E'], v)
            if side == 'O': L(x0, p, x0+depth, p+w, fl, pr, ['O'], v)
            p += w
        assert abs(p - b) < 1e-6, ('côté non rempli', x0, z0, side, p, b)

